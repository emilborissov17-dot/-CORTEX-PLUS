"""
test/test_spine_llm_reach.py — which import edges still let the spine reach the LLM stack.

Task #8 step A, 24 Sep 2026. The spine is fast_cycle_runner.main() minus the steps
named in EDGE_STEPS (moved to the edges runner or retired in step B). A spine step
REACHES the LLM stack when a module its segment imports - its beat()-delimited part of
main(), plus the runner functions it calls - transitively imports a module that
imports core.llm_door.

Step A cut the two chains the plan named: core.phase_tracker -> cockpit.phase_voice
(the voice is now a hook the cycle registers) and core.notary -> core.passage_rules ->
agents.core.self_modifier (a self-test import). Measured after both cuts, 16 edges
still carry the spine into the LLM stack. They are NAMED below: a line there is a
debt, not a dispensation. The test fails on any edge not in the list (a new path to
a model), and on any line whose edge no longer exists (cut it, delete the line).
Zero-reach is reached when KNOWN_EDGES is empty.
"""
from __future__ import annotations

import ast
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOOR = "core.llm_door"
SKIP = {"venv", "venv312_metta", "venv_train", "test", ".git"}

EDGE_STEPS = {
    # moved to the edges runner (task #8 step B)
    "brain_briefing", "civilization_snapshots", "planet_snapshots", "human_snapshots",
    "cosmos_snapshots", "level_reconcile", "constancy_and_constellation", "self_observer",
    "hyperclaw", "hyperclaw_plan", "cortexstrategist", "read_the_mirror", "brain_debrief",
    "brain_reconsider", "auto_levels",
    # retired (the list of 24 Sep)
    "llm_self_review_axes", "internet_intelligence", "planetary_potential", "energy_review",
    "self_awareness", "session_update", "daily_analysis", "growth_planner",
    "action_recommendations", "cortex_scan",
}

KNOWN_EDGES = {
    ("<step>", "core.brain"): "beat() -> memory.heartbeat / brain.attend before every step",
    ("<step>", "core.groq_backend"): "dependency_check reads GROQ_API_URL for its ping (kept, by decision)",
    ("<step>", "core.llm_door"): "boot recomputes LLM timeouts; dependency_check pings Groq",
    ("core.death_bell", "core.brain"): "post-mortem on a death",
    ("experiments.needs.approve_reader", "core.source_registration"): "an approved source is registered with a semantic rule",
    ("hypothesis_generator", "core.groq_backend"): "hypotheses are generated by the ladder",
    ("initiative_tracker", "core.groq_backend"): "notify_patches_and_initiatives",
    ("supervisor", "core.self_diagnosis"): "the supervisor's autopsy",
}


def _modname(p: Path) -> str:
    parts = list(p.relative_to(REPO).with_suffix("").parts)
    return ".".join(parts[:-1] if parts[-1] == "__init__" else parts)


def _graph():
    files = {}
    for p in REPO.rglob("*.py"):
        rel = p.relative_to(REPO).as_posix()
        if set(rel.split("/")[:-1]) & SKIP or "__pycache__" in rel:
            continue
        files[_modname(p)] = p
    imports = {}
    for m, p in files.items():
        try:
            tree = ast.parse(p.read_text(encoding="utf-8-sig"))
        except Exception:
            imports[m] = set()
            continue
        got = set()
        for n in ast.walk(tree):
            if isinstance(n, ast.Import):
                got |= {a.name for a in n.names}
            elif isinstance(n, ast.ImportFrom) and n.module and n.level == 0:
                got.add(n.module)
                got |= {f"{n.module}.{a.name}" for a in n.names}
        imports[m] = {g for g in got if g in files or g == DOOR}
    return files, imports


def _spine_roots(files):
    src = files["fast_cycle_runner"].read_text(encoding="utf-8-sig")
    tree = ast.parse(src)
    funcs = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    top = {}
    for n in tree.body:
        if isinstance(n, ast.Import):
            for a in n.names:
                top[a.asname or a.name.split(".")[0]] = a.name
        elif isinstance(n, ast.ImportFrom) and n.module:
            for a in n.names:
                full = f"{n.module}.{a.name}"
                top[a.asname or a.name] = full if full in files else n.module

    def mods(node, seen):
        out = set()
        for n in ast.walk(node):
            if isinstance(n, ast.Import):
                out |= {a.name for a in n.names}
            elif isinstance(n, ast.ImportFrom) and n.module:
                out.add(n.module)
                out |= {f"{n.module}.{a.name}" for a in n.names}
            elif isinstance(n, ast.Name):
                if n.id in top:
                    out.add(top[n.id])
                if n.id in funcs and n.id not in seen:
                    seen.add(n.id)
                    out |= mods(funcs[n.id], seen)
        return {o for o in out if o in files or o == DOOR}

    roots, label = set(), "(before first beat)"
    for st in funcs["main"].body:
        b = [n for n in ast.walk(st) if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "beat"
             and n.args and isinstance(n.args[0], ast.Constant)]
        if b and isinstance(st, ast.Expr):
            label = b[0].args[0].value
            continue
        if label not in EDGE_STEPS:
            roots |= mods(st, set())
    return roots


def _cut_edges():
    files, imports = _graph()
    direct = {m for m, deps in imports.items() if DOOR in deps and m != DOOR}
    roots = _spine_roots(files)
    edges, seen, frontier = set(), set(), list(roots)
    for r in roots:
        if r in direct or r == DOOR:
            edges.add(("<step>", r))
    while frontier:
        m = frontier.pop()
        if m in seen or m in direct or m == DOOR:
            continue
        seen.add(m)
        for d in imports.get(m, ()):
            if d in direct or d == DOOR:
                edges.add((m, d))
            else:
                frontier.append(d)
    return edges


def test_the_spine_reaches_the_llm_stack_only_through_named_edges():
    edges = _cut_edges()
    new = sorted(edges - set(KNOWN_EDGES))
    gone = sorted(set(KNOWN_EDGES) - edges)
    assert not new, "NEW paths from the spine to a model:\n  " + "\n  ".join(f"{a} -> {b}" for a, b in new)
    assert not gone, "cut, but still listed - delete these lines:\n  " + "\n  ".join(f"{a} -> {b}" for a, b in gone)


def test_the_two_chains_cut_in_step_a_stay_cut():
    _, imports = _graph()
    assert "cockpit.phase_voice" not in imports["core.phase_tracker"]
    assert not any(m.startswith("agents.core.self_modifier") for m in imports["core.passage_rules"])
