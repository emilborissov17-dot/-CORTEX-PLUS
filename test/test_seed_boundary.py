# -*- coding: utf-8 -*-
"""ITEM 12(a) — the exception has a boundary, or it is not an exception.

THE RULE BEING GUARDED. docs/QUEUE.md's standing rules said, absolutely: never
stage data/, V-Dem, CSV, media, .env, or the runtime-churn files under memory/,
snapshots/, news/. On 2026-08-29 Emil approved ONE enumerated exception —
data/seed/ — on Kimi's advice:

    "UNTRACK-AND-SEED. The rule itself should change: data/seed/ must become an
     explicit, enumerated exception to the never-stage rule, constrained to
     .seed.* files generated by a named command and paired with a .provenance
     record. An absolute rule that forces fresh clones to build from zero is
     unreproducible by design."

AND KIMI OBJECTED TO ITS OWN RULING, WHICH IS WHY THIS FILE EXISTS:

    "An enumerated exception is still a hole. A future developer could commit a
     50MB file to data/seed/, call it a seed, and the rule would not stop them
     without additional size or format enforcement."

THIS FILE IS THAT ENFORCEMENT. Four conditions, each of which is a way the hole
gets used:

  1. NAME     — anything in data/seed/ must be *.seed.json or *.seed.provenance.
                Stops "I put it in the seed folder so the rule allows it".
  2. PAIRED   — every seed has a sibling provenance. Stops a snapshot arriving
                with no account of where it came from.
  3. SIZE     — under SEED_MAX_BYTES. This is the 50MB file, refused by number.
  4. SEALED   — the provenance's recorded sha256 must match the seed beside it.
                Stops a seed being edited after generation, which would make the
                provenance a label rather than a seal.

IT RUNS AGAINST THE DIRECTORY, NOT AGAINST tools/make_seed.py. A check that only
fired when the named command ran would be no check at all: the 50MB file arrives
by `cp`, not by running the tool.
"""
from __future__ import annotations

import hashlib
import json
import pathlib

BASE = pathlib.Path(__file__).resolve().parents[1]
SEED_DIR = BASE / "data" / "seed"

# ── THE CEILING, AND WHY IT IS THIS NUMBER ─────────────────────────────────
#
# 5 MiB. The only seed today is axis_history at ~645 KB, so this is roughly
# eight times the real thing: room for the series to keep growing for a long
# while, and still two orders of magnitude below the 50MB file Kimi named.
#
# THE NUMBER IS NOT THE POINT — HAVING ONE IS. A ceiling that can be raised in
# the same commit as the file that breaches it would be theatre, so raising it
# must be argued in the commit body: say what the seed is, why the data cannot
# be smaller, and why the repository should carry it forever. Git history is
# permanent; a large file committed once is committed for good.
#
# If a seed genuinely needs more than this, the honest answer is usually that it
# should not be a seed at all — it should be fetched, not stored.
SEED_MAX_BYTES = 5 * 1024 * 1024

SEED_SUFFIX = ".seed.json"
PROV_SUFFIX = ".seed.provenance"


def _entries():
    if not SEED_DIR.exists():
        return []
    return sorted(p for p in SEED_DIR.rglob("*") if p.is_file())


def test_the_seed_directory_exists_at_all():
    """If this fails the exception is unused, and the standing rule in
    docs/QUEUE.md is describing a mechanism that is not there."""
    assert SEED_DIR.is_dir(), (
        f"{SEED_DIR} does not exist, but docs/QUEUE.md's standing rules name it "
        f"as the one exception to never-stage. Either generate a seed "
        f"(venv/Scripts/python.exe tools/make_seed.py --write) or remove the "
        f"exception — a documented hole with nothing in it is still a hole.")


def test_condition_1_every_file_is_a_seed_or_a_provenance():
    """The folder is not a folder. It is a category with two members."""
    wrong = [p.relative_to(BASE).as_posix() for p in _entries()
             if not (p.name.endswith(SEED_SUFFIX) or p.name.endswith(PROV_SUFFIX))]
    assert not wrong, (
        "these files sit in data/seed/ and are neither a *.seed.json nor a "
        f"*.seed.provenance:\n  " + "\n  ".join(wrong) +
        "\nThe exception covers seeds, not the directory. Putting a file here "
        "does not make it one.")


def test_condition_2_every_seed_has_a_provenance_beside_it():
    """A snapshot with no account of where it came from is the thing the whole
    project refuses. It does not become acceptable by living in data/seed/."""
    orphans = []
    for p in _entries():
        if p.name.endswith(SEED_SUFFIX):
            sib = p.with_name(p.name[: -len(SEED_SUFFIX)] + PROV_SUFFIX)
            if not sib.exists():
                orphans.append(p.relative_to(BASE).as_posix())
    assert not orphans, (
        "these seeds have no sibling *.seed.provenance:\n  " + "\n  ".join(orphans)
        + "\nRegenerate with tools/make_seed.py --write, which writes the pair.")


def test_condition_2b_no_provenance_without_its_seed():
    """The other direction, which is the one that happens by accident: a seed
    deleted or renamed and its provenance left behind, describing nothing."""
    widowed = []
    for p in _entries():
        if p.name.endswith(PROV_SUFFIX):
            sib = p.with_name(p.name[: -len(PROV_SUFFIX)] + SEED_SUFFIX)
            if not sib.exists():
                widowed.append(p.relative_to(BASE).as_posix())
    assert not widowed, (
        "these provenance records describe a seed that is not there:\n  "
        + "\n  ".join(widowed))


def test_condition_3_nothing_exceeds_the_stated_ceiling():
    """KIMI'S 50MB FILE, REFUSED BY NUMBER. This is the assertion the objection
    asked for, and the reason SEED_MAX_BYTES is a named constant with a comment
    rather than a literal in this line."""
    big = [(p.relative_to(BASE).as_posix(), p.stat().st_size)
           for p in _entries() if p.stat().st_size > SEED_MAX_BYTES]
    assert not big, (
        f"these files exceed SEED_MAX_BYTES ({SEED_MAX_BYTES} bytes):\n  "
        + "\n  ".join(f"{n}  {s} bytes" for n, s in big)
        + "\nGit history is permanent: a large file committed once is committed "
          "for good. Raising the ceiling is allowed and must be ARGUED in the "
          "commit body — what the seed is, why it cannot be smaller, and why "
          "this repository should carry it forever. Usually the honest answer "
          "is that it should be fetched, not stored.")


def test_condition_4_the_provenance_is_a_seal_and_not_a_label():
    """The recorded digest must match the seed beside it. Without this the
    provenance is decoration: a seed could be edited by hand after generation and
    still carry a confident-looking record of a file that no longer exists."""
    broken = []
    for p in _entries():
        if not p.name.endswith(PROV_SUFFIX):
            continue
        seed = p.with_name(p.name[: -len(PROV_SUFFIX)] + SEED_SUFFIX)
        if not seed.exists():
            continue                     # covered by test_condition_2b
        try:
            prov = json.loads(p.read_text(encoding="utf-8-sig"))
        except Exception as e:
            broken.append(f"{p.name}: unreadable ({type(e).__name__})")
            continue
        actual = hashlib.sha256(seed.read_bytes()).hexdigest()
        if prov.get("seed_sha256") != actual:
            broken.append(f"{seed.name}: provenance says "
                          f"{prov.get('seed_sha256')!r}, file hashes to {actual}")
    assert not broken, (
        "provenance does not match the seed it describes:\n  " + "\n  ".join(broken)
        + "\nA seed edited after generation breaks its own seal. Regenerate with "
          "tools/make_seed.py --write rather than editing either file by hand.")


def test_the_provenance_says_where_the_data_came_from():
    """A provenance that records only a hash proves the file did not change and
    says nothing about what it IS. These four fields are what a reader needs to
    decide whether to trust the seed at all."""
    required = ("source_path", "source_sha256", "generated_at_utc",
                "generated_at_commit")
    missing = []
    for p in _entries():
        if not p.name.endswith(PROV_SUFFIX):
            continue
        prov = json.loads(p.read_text(encoding="utf-8-sig"))
        for k in required:
            if not prov.get(k):
                missing.append(f"{p.name}: {k}")
    assert not missing, (
        "provenance records missing required fields:\n  " + "\n  ".join(missing))


def test_the_seed_is_not_mistaken_for_the_authority():
    """THE SEED IS NOT A BACKUP AND MUST NOT READ LIKE ONE. If the seed and the
    live file disagree, the live file is right — it is the one the cycles write.
    A record that does not say so invites exactly the restore-over-live-data that
    ITEM 12 exists to prevent."""
    for p in _entries():
        if not p.name.endswith(PROV_SUFFIX):
            continue
        prov = json.loads(p.read_text(encoding="utf-8-sig"))
        assert "NOT AUTHORITATIVE" in (prov.get("authority") or ""), (
            f"{p.name} does not say the seed is not authoritative. That sentence "
            f"is the difference between a starting point and a restore target.")


def test_nothing_outside_data_seed_gained_an_exception():
    """The exception is ONE directory. This fails if a second appears, because
    the way an enumerated exception stops being enumerated is quietly."""
    data = BASE / "data"
    if not data.is_dir():
        return
    suspects = [p.relative_to(BASE).as_posix()
                for p in data.rglob("*.seed.json")
                if SEED_DIR not in p.parents and p.parent != SEED_DIR]
    assert not suspects, (
        "these *.seed.json files live outside data/seed/:\n  "
        + "\n  ".join(suspects)
        + "\nThe never-stage rule names one exception by path. A seed elsewhere "
          "is outside it, whatever it is called.")
