# STATUS / SCORING
# ---------------------------------------------------------------------------

def status():
    rows = _read_jsonl(IDEA_STREAM)
    if not rows:
        return {"stream": str(IDEA_STREAM), "exists": IDEA_STREAM.exists(), "total": 0,
                "note": "no ideas yet - the creative phase has produced nothing"}
    accepted = [r for r in rows if r.get("status") == "accepted"]
    resolved = [r for r in accepted if r.get("outcome") is not None]
    correct = [r for r in resolved if r.get("outcome") is True]
    reasons = {}
    for r in rows:
        if r.get("status") == "rejected":
            reasons[r.get("reject_reason")] = reasons.get(r.get("reject_reason"), 0) + 1
    return {
        "stream": str(IDEA_STREAM),
        "total": len(rows),
        "accepted": len(accepted),
        "mentor_rejected": len([r for r in rows if r.get("status") == "mentor_rejected"]),
        "guard_rejected": len([r for r in rows if r.get("status") == "rejected"]),
        "reject_reasons": reasons,
        "resolved": len(resolved),
        "correct": len(correct),
        "predictive_accuracy": (round(len(correct) / len(resolved), 3) if resolved else None),
        "NOT_A_METRIC": "accept-rate. Never report it as quality. An idea generator scored on approval learns to please.",
    }


def due():
    now = _now()
    out = []
    for r in _read_jsonl(IDEA_STREAM):
        if r.get("status") != "accepted" or r.get("outcome") is not None:
            continue
        h = r.get("test_horizon")
        if not h:
            continue
        dt = _try(lambda: datetime.strptime(h, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc))
        if dt and dt <= now:
            out.append(r)
    return out


def selftest():
    """Report which parts of this module are actually live in THIS repo.

    Exists because a module that degrades silently lets a claim like 'the
    mentor pass checks each idea' stay true on paper and false on disk.
    """
    oracle = _load_metta_oracle()
    llm = _load_llm()
    report = {
        "repo_root": str(REPO),
        "idea_stream": str(IDEA_STREAM),
        "idea_stream_exists": IDEA_STREAM.exists(),
        "seed_gen_1_rule_violations": "LIVE" if oracle else "INERT - core.metta_oracle not importable",
        "seed_gen_2_trends": "LIVE (pure python, no dependency)",
        "mentor_pass": "LIVE" if oracle else "INERT - every idea surfaces unchecked",
        "penumbra_model_anomaly_door": "REACHABLE" if oracle else "UNREACHABLE",
        "articulation": "LLM" if llm else "deterministic fallback - core.groq_backend.call_groq not importable",
        "guards": ["grounded_on refs must exist on disk", "falsifiable_test required",
                   "integer horizon_days required", "would_be_false_if required",
                   "non-ASCII output rejected as non_english_output"],
        "writes": [str(IDEA_STREAM)],
        "actuates": "nothing",
    }
    degraded = [k for k, v in report.items() if isinstance(v, str) and ("INERT" in v or "UNREACHABLE" in v)]
    report["DEGRADED"] = degraded or "none"
    return report


def main():
    ap = argparse.ArgumentParser(description="CORTEX background creative tick")
    ap.add_argument("--selftest", action="store_true", help="report which integrations are actually live")
    ap.add_argument("--dry-run", action="store_true", help="print, write nothing")
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--due", action="store_true", help="ideas whose horizon has passed and await a verdict")
    ap.add_argument("--levels", default=None, help="path to a JSON file of current axis levels")
    ap.add_argument("--series", default=None, help="path to a JSON file of {axis: [values]}")
    args = ap.parse_args()

    if args.selftest:
        print(json.dumps(selftest(), indent=2))
        return 0
    if args.status:
        st = status()
        st["integrations"] = {k: v for k, v in selftest().items()
                              if k.startswith("seed_gen") or k in ("mentor_pass", "articulation", "DEGRADED")}
        print(json.dumps(st, indent=2))
        return 0
    if args.due:
        for r in due():
            print(json.dumps({"seed_key": r["seed_key"], "idea": r["idea"],
                              "test": r["falsifiable_test"], "horizon": r["test_horizon"]}, indent=2))
        return 0

    levels = json.loads(Path(args.levels).read_text(encoding="utf-8")) if args.levels else {}
    series = json.loads(Path(args.series).read_text(encoding="utf-8")) if args.series else {}
    grounded = [p for p in ("memory/existence_ledger.jsonl", "config/target_config.json") if (REPO / p).exists()]
    recs = run_tick(levels, series, grounded, dry_run=args.dry_run)
    print("creative_tick: %d records (%d accepted)" % (
        len(recs), len([r for r in recs if r.get("status") == "accepted"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
